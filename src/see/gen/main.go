// Command gen regenerates ../resource_mapping.go from schema/*.json.
//
// It preserves existing CFN→Terraform values from the current file, adds any
// schema typeNames that are missing (defaulting to none), drops AWS entries
// whose schema file has been removed, and carries all microsoft.* entries
// through untouched. Run from the repo root: go run ./src/see/gen
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	schemaDir  = "schema"
	targetFile = "src/see/resource_mapping.go"
	noneToken  = "none"
)

var entryRe = regexp.MustCompile(`^\s*"([^"]+)":\s+(.+?),(?:\s*//.*)?$`)

type schemaHeader struct {
	TypeName string `json:"typeName"`
}

func main() {
	existing, err := readExisting(targetFile)
	if err != nil {
		fatal("read existing mappings: %v", err)
	}

	cfnTypes, err := readSchemaTypes(schemaDir)
	if err != nil {
		fatal("read schema dir: %v", err)
	}

	aws := make(map[string]string, len(cfnTypes))
	var added, removed []string

	for _, t := range cfnTypes {
		if v, ok := existing[t]; ok {
			aws[t] = v
		} else {
			aws[t] = noneToken
			added = append(added, t)
		}
	}

	arm := make(map[string]string)
	for k, v := range existing {
		if strings.HasPrefix(k, "microsoft.") {
			arm[k] = v
			continue
		}
		if _, ok := aws[k]; !ok {
			removed = append(removed, k)
		}
	}

	if err := writeTarget(targetFile, aws, arm); err != nil {
		fatal("write %s: %v", targetFile, err)
	}

	report("added (defaulted to none)", added)
	report("removed (no schema file)", removed)
	fmt.Fprintf(os.Stderr, "wrote %s: %d AWS + %d ARM entries\n", targetFile, len(aws), len(arm))
}

func readExisting(path string) (map[string]string, error) {
	f, err := os.Open(path) // #nosec G304
	if err != nil {
		return nil, err
	}
	defer f.Close() //nolint:errcheck // read-only file

	out := make(map[string]string)
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := entryRe.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		out[m[1]] = strings.TrimSpace(m[2])
	}
	return out, sc.Err()
}

func readSchemaTypes(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	types := make([]string, 0, len(entries))
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".json" {
			continue
		}
		t, err := typeNameFromFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", e.Name(), err)
		}
		types = append(types, strings.ToLower(t))
	}
	return types, nil
}

func typeNameFromFile(path string) (string, error) {
	f, err := os.Open(path) // #nosec G304
	if err != nil {
		return "", err
	}
	defer f.Close() //nolint:errcheck // read-only file

	var hdr schemaHeader
	if err := json.NewDecoder(f).Decode(&hdr); err != nil {
		return "", err
	}
	if hdr.TypeName == "" {
		return "", fmt.Errorf("missing typeName")
	}
	return hdr.TypeName, nil
}

func writeTarget(path string, aws, arm map[string]string) error {
	var b strings.Builder
	b.WriteString("// Code generated by go run ./src/see/gen; DO NOT EDIT.\n")
	b.WriteString("// Edit terraform targets in place, then re-run the generator to re-sort\n")
	b.WriteString("// and pick up new CloudFormation types from schema/.\n\n")
	b.WriteString("package see\n\n")
	b.WriteString("//goland:noinspection GoLinter\n")
	b.WriteString("var lookupMapping = map[string]string{\n")

	writeSection(&b, aws)
	if len(arm) > 0 {
		b.WriteString("\n\t// Azure ARM (hand-maintained, no schema source)\n")
		writeSection(&b, arm)
	}
	b.WriteString("}\n")

	return os.WriteFile(path, []byte(b.String()), 0o644) // #nosec G306
}

func writeSection(b *strings.Builder, m map[string]string) {
	keys := make([]string, 0, len(m))
	width := 0
	for k := range m {
		keys = append(keys, k)
		if len(k) > width {
			width = len(k)
		}
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%-*s %s,\n", width+3, `"`+k+`":`, m[k])
	}
}

func report(label string, items []string) {
	if len(items) == 0 {
		return
	}
	sort.Strings(items)
	fmt.Fprintf(os.Stderr, "%s: %d\n", label, len(items))
	for _, it := range items {
		fmt.Fprintf(os.Stderr, "  %s\n", it)
	}
}

func fatal(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "seegen: "+format+"\n", a...)
	os.Exit(1)
}
